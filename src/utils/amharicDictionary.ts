/**
 * Resolves an English word (case-insensitive) into pure Amharic using:
 * 0) Preserved academic proper names, SI units, and classical roots (Rule 4)
 * 1) Direct dictionary match (checked BEFORE acronym filter so emphasis like NOT/ONLY translates)
 * 2) Acronym & Roman numeral preservation (DNA, ATP, GDP, AI, II, III, IV)
 * 3) Prefix / hyphen / suffix stem resolution
 * 4) Ethiopic Fidel transliteration for remaining scientific/taxonomic loanwords
 */
export function translateEnglishWordToAmharic(rawWord: string): string | null {
  if (!rawWord) return null;
  const lower = rawWord.toLowerCase();

  // Keep single-letter variables/initials unless 'a'
  if (rawWord.length === 1) {
    if (lower === 'a') return '';
    return null;
  }

  // Handle possessive 's
  if (lower.endsWith("'s") || lower.endsWith('’s')) {
    const base = rawWord.slice(0, -2);
    if (PRESERVED_ACADEMIC_PROPER_AND_UNIT_TERMS.has(base.toLowerCase())) {
      return `የ${base}`;
    }
    const baseAm = translateEnglishWordToAmharic(base);
    return baseAm ? `የ${baseAm}` : null;
  }

  if (DROPPABLE_ARTICLES.has(lower)) {
    return '';
  }

  // Rule 4: Keep SI units, classical academic roots & named theorists/scientists in English
  if (PRESERVED_ACADEMIC_PROPER_AND_UNIT_TERMS.has(lower)) {
    return null;
  }

  // Check exact dictionary match FIRST (handles uppercase emphasis like NOT, ALWAYS, NEVER, ONLY)
  if (AMHARIC_WORD_DICT[lower] !== undefined) {
    return AMHARIC_WORD_DICT[lower];
  }

  // Keep Roman numerals & standard short all-caps acronyms (DNA, ATP, GDP, AI, IoT, UN, AU, pH, SI)
  if (
    ROMAN_NUMERALS.has(lower) ||
    /^[A-Z0-9]{2,7}$/.test(rawWord) ||
    rawWord === 'IoT' ||
    rawWord === 'pH' ||
    rawWord === 'mRNA' ||
    rawWord === 'tRNA' ||
    rawWord === 'rRNA'
  ) {
    return null;
  }

  // Prefixes like non-violent, sub-Saharan, anti-colonial (check BEFORE generic hyphen split)
  for (const [pref, prefAm] of PREFIX_MAP) {
    if (lower.startsWith(pref) && lower.length > pref.length + 2) {
      const rest = lower.slice(pref.length);
      const restAm = AMHARIC_WORD_DICT[rest] || translateEnglishWordToAmharic(rest);
      if (restAm) return `${prefAm}${restAm}`;
    }
  }

  // Hyphenated compound (e.g., teacher-based, city-state, socio-economic)
  if (rawWord.includes('-')) {
    const parts = rawWord.split('-');
    const translatedParts = parts.map((p) => translateEnglishWordToAmharic(p) || p);
    const anyChanged = parts.some((p, idx) => translatedParts[idx] !== p);
    if (anyChanged) {
      return translatedParts.filter(Boolean).join(' ');
    }
  }

  if (lower.startsWith('un') && lower.length > 4) {
    const rest = lower.slice(2);
    if (AMHARIC_WORD_DICT[rest]) return `${AMHARIC_WORD_DICT[rest]} ያልሆነ`;
  }
  if (lower.startsWith('dis') && lower.length > 5) {
    const rest = lower.slice(3);
    if (AMHARIC_WORD_DICT[rest]) return `አለመ${AMHARIC_WORD_DICT[rest]}`;
  }

  // Suffixes: -ies -> -y
  if (lower.endsWith('ies') && lower.length > 4) {
    const base = lower.slice(0, -3) + 'y';
    if (AMHARIC_WORD_DICT[base]) return AMHARIC_WORD_DICT[base];
  }
  // -es / -s
  if (lower.endsWith('es') && lower.length > 3) {
    const b1 = lower.slice(0, -2);
    const b2 = lower.slice(0, -1);
    if (AMHARIC_WORD_DICT[b1]) return AMHARIC_WORD_DICT[b1];
    if (AMHARIC_WORD_DICT[b2]) return AMHARIC_WORD_DICT[b2];
  }
  if (lower.endsWith('s') && lower.length > 3 && !lower.endsWith('ss')) {
    const b = lower.slice(0, -1);
    if (AMHARIC_WORD_DICT[b]) return AMHARIC_WORD_DICT[b];
  }

  // -ied -> -y, -ed -> base / base+'e'
  if (lower.endsWith('ied') && lower.length > 4) {
    const b = lower.slice(0, -3) + 'y';
    if (AMHARIC_WORD_DICT[b]) return AMHARIC_WORD_DICT[b];
  }
  if (lower.endsWith('ed') && lower.length > 4) {
    const b1 = lower.slice(0, -2);
    const b2 = lower.slice(0, -1);
    if (AMHARIC_WORD_DICT[b1]) return AMHARIC_WORD_DICT[b1];
    if (AMHARIC_WORD_DICT[b2]) return AMHARIC_WORD_DICT[b2];
  }

  // -ing -> base+'e' / base
  if (lower.endsWith('ing') && lower.length >= 5) {
    const b1 = lower.slice(0, -3);
    const b2 = lower.slice(0, -3) + 'e';
    if (AMHARIC_WORD_DICT[b2]) return AMHARIC_WORD_DICT[b2];
    if (AMHARIC_WORD_DICT[b1] && b1 !== 'us') return AMHARIC_WORD_DICT[b1];
  }

  // -ly -> base adjective + በ... መልኩ
  if (lower.endsWith('ly') && lower.length > 4) {
    const b1 = lower.slice(0, -2);
    const b2 = lower.endsWith('ally') ? lower.slice(0, -4) : '';
    const b3 = lower.endsWith('ically') ? lower.slice(0, -6) + 'ic' : '';
    const b4 = lower.endsWith('ily') ? lower.slice(0, -3) + 'y' : '';
    const found =
      AMHARIC_WORD_DICT[b1] ||
      (b2 && AMHARIC_WORD_DICT[b2]) ||
      (b3 && AMHARIC_WORD_DICT[b3]) ||
      (b4 && AMHARIC_WORD_DICT[b4]);
    if (found) return `በ${found} መልኩ`;
  }

  // -ization / -ness / -ity
  if (lower.endsWith('ization') && lower.length > 8) {
    const b = lower.slice(0, -7) + 'ize';
    if (AMHARIC_WORD_DICT[b]) return AMHARIC_WORD_DICT[b];
  }
  if (lower.endsWith('ness') && lower.length > 6) {
    const b = lower.slice(0, -4);
    if (AMHARIC_WORD_DICT[b]) return `${AMHARIC_WORD_DICT[b]}ነት`;
  }
  if (lower.endsWith('ity') && lower.length > 5) {
    const b1 = lower.slice(0, -3);
    const b2 = lower.slice(0, -3) + 'e';
    if (AMHARIC_WORD_DICT[b1]) return `${AMHARIC_WORD_DICT[b1]}ነት`;
    if (AMHARIC_WORD_DICT[b2]) return `${AMHARIC_WORD_DICT[b2]}ነት`;
  }

  // Final fallback for scientific/technical loanwords & unmapped Latin words (>= 3 chars)
  if (lower.length >= 3 && /^[a-z]+$/.test(lower)) {
    return transliterateLoanwordToFidel(lower);
  }

  return null;
}

