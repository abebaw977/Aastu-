function vowelOrderIndex(v: string): number {
  switch (v) {
    case 'e': return 4; // é / e -> order 5 (e.g. ሜ, ቤ)
    case 'u': return 1;
    case 'i': return 2;
    case 'a': return 3;
    case 'o': return 6;
    default: return 5;
  }
}

/**
 * Phonetic Ethiopic Fidel transliterator for untranslated scientific/taxonomic loanwords
 * (e.g., gametophyte -> ጋሜቶፋይት, chlorophyta -> ክሎሮፋይታ, rhizoids -> ራይዞይድስ).
 */
function transliterateLoanwordToFidel(word: string): string {
  let w = word.toLowerCase().replace(/[^a-z]/g, '');
  if (!w) return word;

  // Common scientific/academic spelling normalizations before syllable mapping
  w = w
    .replace(/tious|cious/g, 'shis')
    .replace(/tions/g, 'shins')
    .replace(/sions/g, 'zhins')
    .replace(/tion/g, 'shin')
    .replace(/sion/g, 'zhin')
    .replace(/phyte/g, 'fayt')
    .replace(/phyta/g, 'fayta')
    .replace(/phy/g, 'fi')
    .replace(/chlor/g, 'klor')
    .replace(/chrom/g, 'krom')
    .replace(/psych/g, 'sayk')
    .replace(/wh/g, 'w')
    .replace(/igh/g, 'ay')
    .replace(/kn/g, 'n')
    .replace(/wr/g, 'r')
    .replace(/eu/g, 'yu')
    .replace(/oo/g, 'u')
    .replace(/ee/g, 'i')
    .replace(/ea/g, 'i')
    .replace(/ai|ay/g, 'ey')
    .replace(/oi|oy/g, 'oy')
    .replace(/qu/g, 'kw')
    .replace(/ck/g, 'k')
    .replace(/x/g, 'ks')
    .replace(/rh/g, 'r')
    .replace(/th/g, 't')
    // Protect 'ch' before softening/hardening single 'c'
    .replace(/ch/g, '\u0001')
    .replace(/c([eiy])/g, 's$1')
    .replace(/c/g, 'k')
    .replace(/\u0001/g, 'ch')
    .replace(/(.)\1+/g, '$1');

  // Drop silent final 'e' on multi-syllable words (e.g., gametophyte -> gametophyt -> ጋሜቶፋይት)
  if (w.length > 3 && w.endsWith('e') && !/[aeiou]e$/.test(w)) {
    w = w.slice(0, -1);
  }

  let out = '';
  let i = 0;
  while (i < w.length) {
    const two = w.slice(i, i + 2);
    const ch = w[i];

    // Special handling for 'y' acting as vowel 'i/ay' between consonants
    if (ch === 'y' && i > 0 && !/[aeiou]/.test(w[i - 1])) {
      out += i + 1 < w.length && /[aeiou]/.test(w[i + 1]) ? '' : 'ይ';
      if (i + 1 < w.length && /[aeiou]/.test(w[i + 1])) {
        const order = vowelOrderIndex(w[i + 1]);
        out += CONSONANT_ORDERS.y[order];
        i += 2;
        continue;
      }
      i++;
      continue;
    }

    if (VOWEL_ONLY[ch]) {
      out += VOWEL_ONLY[ch];
      i++;
      continue;
    }

    let consKey: string | null = null;
    let step = 1;
    if (CONSONANT_ORDERS[two]) {
      consKey = two;
      step = 2;
    } else if (CONSONANT_ORDERS[ch]) {
      consKey = ch;
      step = 1;
    }

    if (!consKey) {
      i++;
      continue;
    }

    const nextChar = w[i + step] || '';
    if (VOWEL_ONLY[nextChar]) {
      const order = vowelOrderIndex(nextChar);
      out += CONSONANT_ORDERS[consKey][order];
      i += step + 1;
    } else {
      out += CONSONANT_ORDERS[consKey][5]; // 6th order (consonant alone)
      i += step;
    }
  }

  return out || word;
}

